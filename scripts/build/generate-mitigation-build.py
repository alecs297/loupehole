#!/usr/bin/env python3
"""Generate Loupehole build inputs from catalog and selection JSON.

The generator is intentionally the only place that turns source-level
declarations into generated C/Make/package artifacts. It validates the selected
mitigation graph, scans selected sources for policy seed declarations, derives
generated bytes from the build seed, and writes disposable outputs for the
runtime, Theos build, Settings bundle, and deb package layout.
"""
import argparse
import hashlib
import json
import os
import re
import shutil
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
ID_RE = re.compile(r"^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*){3,}$")
UUID_RE = re.compile(r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$")
STATUSES = {"planned", "experimental", "beta", "stable", "deprecated"}
LABEL_NAMESPACE = b"lh.derivation-label.v1\0"
POLICY_SEED_NAMESPACE = b"lh.policy-seed.v1\0"
PACKAGE_STATE_PARENT_NAMESPACE = b"lh.package-state-parent.v1\0"
PACKAGE_SEED_ROOT_DIRECTORY_NAMESPACE = b"lh.package-seed-root-directory.v1\0"
PACKAGE_ROOT_SEED_FILE_NAMESPACE = b"lh.package-root-seed-file.v1\0"
PACKAGE_POLICY_FILE_NAMESPACE = b"lh.package-policy-file.v1\0"
PACKAGE_LOADER_BASENAME_NAMESPACE = b"lh.package-loader-basename.v1\0"
LABEL_COMPONENT_RE = re.compile(r"^[a-z][a-z0-9_]*$")
LABEL_DECL_RE = re.compile(r"\bLH_DERIVATION_LABEL\s*\(\s*([a-z][a-z0-9_]*)\s*,\s*([a-z][a-z0-9_]*)\s*\)")
POLICY_SEED_DECL_RE = re.compile(
    r'\bLH_POLICY_SEED\s*\(\s*([a-z][a-z0-9_]*)\s*,\s*([a-z][a-z0-9_]*)\s*,\s*("(?:[^"\\]|\\.)*")\s*\)'
)


def load_json(path):
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def as_list(value, name):
    if value is None:
        return []
    if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
        raise SystemExit(f"{name} must be a list of strings")
    return value


def symbol_for(identifier):
    return "LHMitigation_" + identifier.replace(".", "_") + "_install"


def enum_for(identifier):
    return "LHModuleID_" + identifier.replace(".", "_")


def label_symbol_for(identifier):
    return "LHGeneratedDerivationLabel_" + identifier.replace(".", "_")


def policy_seed_symbol_for(identifier):
    return "LHGeneratedPolicySeed_" + identifier.replace(".", "_")


def parse_uuid_bytes(value, name):
    if value is None:
        return None
    if not isinstance(value, str) or not UUID_RE.match(value):
        raise SystemExit(f"{name} must be a UUID string")
    return bytes.fromhex(value.replace("-", ""))


def label_bytes_for(identifier, build_seed):
    seed = build_seed if build_seed is not None else b""
    digest = hashlib.sha256(LABEL_NAMESPACE + seed + b"\0" + identifier.encode("utf-8")).digest()
    return digest[:16]


def policy_seed_bytes_for(literal, build_seed):
    seed = build_seed if build_seed is not None else b""
    digest = hashlib.sha256(POLICY_SEED_NAMESPACE + seed + b"\0" + literal.encode("utf-8")).digest()
    return digest[:16]


def byte_initializer(data):
    return "{ " + ", ".join(f"0x{byte:02x}" for byte in data) + " }"


def generated_hex_name(namespace, build_seed):
    seed = build_seed if build_seed is not None else b""
    return hashlib.sha256(namespace + seed).hexdigest()[:32]


def package_state_parent_name(build_seed):
    return generated_hex_name(PACKAGE_STATE_PARENT_NAMESPACE, build_seed)


def package_seed_root_directory_name(build_seed):
    return generated_hex_name(PACKAGE_SEED_ROOT_DIRECTORY_NAMESPACE, build_seed)


def package_root_seed_file_name(build_seed):
    return generated_hex_name(PACKAGE_ROOT_SEED_FILE_NAMESPACE, build_seed)


def package_policy_file_name(build_seed):
    return generated_hex_name(PACKAGE_POLICY_FILE_NAMESPACE, build_seed)


def package_loader_basename(build_seed):
    seed = build_seed if build_seed is not None else b""
    return "x" + hashlib.sha256(PACKAGE_LOADER_BASENAME_NAMESPACE + seed).hexdigest()[:31]


def normalize_catalog(catalog):
    """Validate mitigation catalog entries and fill default build metadata."""
    defaults = catalog.get("defaults", {})
    raw = catalog.get("mitigations", [])
    if not isinstance(raw, list):
        raise SystemExit("catalog mitigations must be a list")

    mitigations = {}
    for item in raw:
        if not isinstance(item, dict):
            raise SystemExit("each mitigation must be an object")

        identifier = item.get("id")
        if not isinstance(identifier, str) or not ID_RE.match(identifier):
            raise SystemExit(f"invalid mitigation id: {identifier}")
        if identifier in mitigations:
            raise SystemExit(f"duplicate mitigation id: {identifier}")

        sources = as_list(item.get("sources"), f"{identifier}.sources")
        if not sources:
            raise SystemExit(f"{identifier} must list at least one source")
        for source in sources:
            if not (ROOT / source).is_file():
                raise SystemExit(f"{identifier} source does not exist: {source}")

        status = item.get("status")
        if status not in STATUSES:
            raise SystemExit(f"{identifier} status must be one of {sorted(STATUSES)}")

        normalized = dict(item)
        for key in ("requires", "conflicts", "frameworks", "weakFrameworks", "libraries"):
            normalized[key] = as_list(item.get(key, defaults.get(key, [])), f"{identifier}.{key}")
        normalized["minIos"] = item.get("minIos", defaults.get("minIos", "15.0"))
        normalized["maxIos"] = item.get("maxIos", defaults.get("maxIos"))
        normalized["symbol"] = symbol_for(identifier)
        normalized["enum"] = enum_for(identifier)
        mitigations[identifier] = normalized

    for identifier, item in mitigations.items():
        for key in ("requires", "conflicts"):
            for dependency in item[key]:
                if dependency not in mitigations:
                    raise SystemExit(f"{identifier} references unknown {key} mitigation: {dependency}")

    return mitigations


def source_for_label_scan(text):
    """Return source text with comments and string literals blanked for label scan."""
    output = []
    state = "code"
    i = 0
    while i < len(text):
        char = text[i]
        next_char = text[i + 1] if i + 1 < len(text) else ""

        if state == "code":
            if char == "/" and next_char == "/":
                output.extend("  ")
                i += 2
                state = "line_comment"
                continue
            if char == "/" and next_char == "*":
                output.extend("  ")
                i += 2
                state = "block_comment"
                continue
            if char == '"':
                output.append(" ")
                i += 1
                state = "string"
                continue
            if char == "'":
                output.append(" ")
                i += 1
                state = "char"
                continue
            output.append(char)
            i += 1
            continue

        if state == "line_comment":
            if char == "\n":
                output.append("\n")
                state = "code"
            else:
                output.append(" ")
            i += 1
            continue

        if state == "block_comment":
            if char == "*" and next_char == "/":
                output.extend("  ")
                i += 2
                state = "code"
                continue
            output.append("\n" if char == "\n" else " ")
            i += 1
            continue

        if state in ("string", "char"):
            if char == "\\" and next_char:
                output.extend("  ")
                i += 2
                continue
            if (state == "string" and char == '"') or (state == "char" and char == "'"):
                output.append(" ")
                i += 1
                state = "code"
                continue
            output.append("\n" if char == "\n" else " ")
            i += 1

    return "".join(output)


def source_for_policy_seed_scan(text):
    """Return source text with comments blanked while preserving string literals."""
    output = []
    state = "code"
    i = 0
    while i < len(text):
        char = text[i]
        next_char = text[i + 1] if i + 1 < len(text) else ""

        if state == "code":
            if char == "/" and next_char == "/":
                output.extend("  ")
                i += 2
                state = "line_comment"
                continue
            if char == "/" and next_char == "*":
                output.extend("  ")
                i += 2
                state = "block_comment"
                continue
            output.append(char)
            if char == '"':
                state = "string"
            elif char == "'":
                state = "char"
            i += 1
            continue

        if state == "line_comment":
            if char == "\n":
                output.append("\n")
                state = "code"
            else:
                output.append(" ")
            i += 1
            continue

        if state == "block_comment":
            if char == "*" and next_char == "/":
                output.extend("  ")
                i += 2
                state = "code"
                continue
            output.append("\n" if char == "\n" else " ")
            i += 1
            continue

        if state in ("string", "char"):
            output.append(char)
            if char == "\\" and next_char:
                output.append(next_char)
                i += 2
                continue
            if (state == "string" and char == '"') or (state == "char" and char == "'"):
                state = "code"
            i += 1

    return "".join(output)


def discover_derivation_labels(source_paths, build_seed):
    """Collect generated internal derivation labels from runtime source files."""
    labels = []
    seen = {}
    for source in source_paths:
        path = ROOT / source
        text = path.read_text(encoding="utf-8")
        scan_text = source_for_label_scan(text)
        for match in LABEL_DECL_RE.finditer(scan_text):
            domain, name = match.groups()
            if not LABEL_COMPONENT_RE.match(domain) or not LABEL_COMPONENT_RE.match(name):
                line = scan_text.count("\n", 0, match.start()) + 1
                raise SystemExit(f"invalid derivation label declaration in {source}:{line}")
            identifier = f"{domain}.{name}"
            line = scan_text.count("\n", 0, match.start()) + 1
            if identifier in seen:
                first_source, first_line = seen[identifier]
                raise SystemExit(
                    f"duplicate derivation label id {identifier}: "
                    f"{source}:{line} also declared in {first_source}:{first_line}"
                )
            seen[identifier] = (source, line)
            labels.append({
                "id": identifier,
                "symbol": label_symbol_for(identifier),
                "bytes": label_bytes_for(identifier, build_seed),
            })

    return labels


def discover_policy_seeds(source_paths, build_seed):
    """Collect selected tweak policy seeds and derive their generated bytes."""
    seeds = []
    seen = {}
    for source in source_paths:
        path = ROOT / source
        text = path.read_text(encoding="utf-8")
        scan_text = source_for_policy_seed_scan(text)
        for match in POLICY_SEED_DECL_RE.finditer(scan_text):
            domain, name, literal_token = match.groups()
            if not LABEL_COMPONENT_RE.match(domain) or not LABEL_COMPONENT_RE.match(name):
                line = scan_text.count("\n", 0, match.start()) + 1
                raise SystemExit(f"invalid policy seed declaration in {source}:{line}")
            try:
                literal = json.loads(literal_token)
            except json.JSONDecodeError as exc:
                line = scan_text.count("\n", 0, match.start()) + 1
                raise SystemExit(f"invalid policy seed literal in {source}:{line}: {exc}") from exc
            if not isinstance(literal, str) or len(literal) == 0:
                line = scan_text.count("\n", 0, match.start()) + 1
                raise SystemExit(f"policy seed literal must be a non-empty string in {source}:{line}")

            identifier = f"{domain}.{name}"
            line = scan_text.count("\n", 0, match.start()) + 1
            if identifier in seen:
                previous_literal, first_source, first_line = seen[identifier]
                if previous_literal != literal:
                    raise SystemExit(
                        f"policy seed id {identifier} uses different literals: "
                        f"{first_source}:{first_line} and {source}:{line}"
                    )
                continue
            seen[identifier] = (literal, source, line)
            seeds.append({
                "id": identifier,
                "symbol": policy_seed_symbol_for(identifier),
                "bytes": policy_seed_bytes_for(literal, build_seed),
            })

    return seeds


def validate_selection(selection, mitigations):
    """Validate the build selection against the normalized mitigation catalog."""
    selected = selection.get("mitigations")
    if not isinstance(selected, list) or not all(isinstance(item, str) for item in selected):
        raise SystemExit("selection mitigations must be a list of strings")
    if len(selected) != len(set(selected)):
        raise SystemExit("selection contains duplicate mitigations")

    selected_set = set(selected)
    for identifier in selected:
        if identifier not in mitigations:
            raise SystemExit(f"selected mitigation is not in catalog: {identifier}")
        item = mitigations[identifier]
        for required in item["requires"]:
            if required not in selected_set:
                raise SystemExit(f"{identifier} requires {required}")
        for conflict in item["conflicts"]:
            if conflict in selected_set:
                raise SystemExit(f"{identifier} conflicts with {conflict}")

    selected_mitigations = [mitigations[identifier] for identifier in selected]

    return selected_mitigations


def make_words(items):
    return " ".join(dict.fromkeys(items))


def selected_source_paths(selected):
    sources = []
    for item in selected:
        sources.extend(item["sources"])
    return list(dict.fromkeys(sources))


def core_derivation_label_source_paths():
    sources = []
    for folder in ("src/runtime", "src/tweakkit"):
        root = ROOT / folder
        for suffix in ("*.c", "*.m", "*.mm"):
            sources.extend(str(path.relative_to(ROOT)) for path in sorted(root.rglob(suffix)))
    return sources


def write_file(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def write_executable(path, text):
    write_file(path, text)
    path.chmod(0o755)


def emit_make_fragment(selected, loader_basename):
    """Write the Theos make fragment for selected sources and link metadata."""
    sources = []
    frameworks = []
    weak_frameworks = []
    libraries = []
    for item in selected:
        sources.extend(os.path.relpath(ROOT / source, ROOT / "packaging/theos") for source in item["sources"])
        frameworks.extend(item["frameworks"])
        weak_frameworks.extend(item["weakFrameworks"])
        libraries.extend(item["libraries"])

    lines = [
        "# Generated by scripts/build/generate-mitigation-build.py.",
        "LH_LOADER_BASENAME := " + loader_basename,
        "LH_SELECTED_MITIGATION_SOURCES := " + make_words(sources),
        "LH_SELECTED_FRAMEWORKS := " + make_words(frameworks),
        "LH_SELECTED_WEAK_FRAMEWORKS := " + make_words(weak_frameworks),
        "LH_SELECTED_LIBRARIES := " + make_words(libraries),
        "",
    ]
    write_file(ROOT / "packaging/theos/generated/mitigation-files.mk", "\n".join(lines))


def emit_registry(catalog_items, selected):
    """Write the generated mitigation registry used by the runtime."""
    enum_lines = []
    extern_lines = []
    descriptor_lines = []
    for item in catalog_items:
        enum_lines.append(f"    {item['enum']} = {item['moduleID']},")
    for item in selected:
        extern_lines.append(f"LH_INTERNAL bool {item['symbol']}(LHHookBackend *backend, LHPolicyEngine *policy);")
        descriptor_lines.append(f"    {{ {item['enum']}, {item['symbol']} }},")

    header = "\n".join([
        "#ifndef LH_GENERATED_MITIGATION_REGISTRY_H",
        "#define LH_GENERATED_MITIGATION_REGISTRY_H",
        "",
        "#include \"LHModuleRegistry.h\"",
        "",
        "#ifdef __cplusplus",
        "extern \"C\" {",
        "#endif",
        "",
        "typedef enum LHGeneratedModuleID {",
        *enum_lines,
        "} LHGeneratedModuleID;",
        "",
        "LH_INTERNAL extern const LHModuleDescriptor LHGeneratedModuleDescriptors[];",
        "LH_INTERNAL extern const size_t LHGeneratedModuleDescriptorCount;",
        "",
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
        "#endif",
        "",
    ])

    source = "\n".join([
        "#include \"LHGeneratedMitigationRegistry.h\"",
        "",
        *extern_lines,
        "",
        "LH_INTERNAL const LHModuleDescriptor LHGeneratedModuleDescriptors[] = {",
        *descriptor_lines,
        "};",
        "",
        "LH_INTERNAL const size_t LHGeneratedModuleDescriptorCount = sizeof(LHGeneratedModuleDescriptors) / sizeof(LHGeneratedModuleDescriptors[0]);",
        "",
    ])

    write_file(ROOT / "core/generated/LHGeneratedMitigationRegistry.h", header)
    write_file(ROOT / "core/generated/LHGeneratedMitigationRegistry.c", source)


def emit_derivation_labels(labels):
    """Write generated internal derivation-label declarations and definitions."""
    extern_lines = []
    definition_lines = []
    for item in labels:
        extern_lines.append(f"LH_INTERNAL extern const LHDerivationLabel {item['symbol']};")
        definition_lines.extend([
            f"LH_INTERNAL const LHDerivationLabel {item['symbol']} = {{",
            f"    .bytes = {byte_initializer(item['bytes'])}",
            "};",
            "",
        ])

    header = "\n".join([
        "#ifndef LH_GENERATED_DERIVATION_LABELS_H",
        "#define LH_GENERATED_DERIVATION_LABELS_H",
        "",
        "#include \"LHSeed.h\"",
        "",
        "#ifdef __cplusplus",
        "extern \"C\" {",
        "#endif",
        "",
        *extern_lines,
        "",
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
        "#endif",
        "",
    ])

    source = "\n".join([
        "#include \"LHGeneratedDerivationLabels.h\"",
        "",
        *definition_lines,
    ])

    write_file(ROOT / "core/generated/LHGeneratedDerivationLabels.h", header)
    write_file(ROOT / "core/generated/LHGeneratedDerivationLabels.c", source)


